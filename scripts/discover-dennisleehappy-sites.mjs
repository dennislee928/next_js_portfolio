/**
 * Discover every site published under the owner's root domains, then classify
 * each host so the portfolio only ever surfaces real frontends.
 *
 * Pipeline: enumerate -> probe -> classify -> dedupe -> report.
 *
 * Enumeration is the part the previous version was missing. It used to rebuild
 * its candidate list from URLs already present in the portfolio, so it could
 * only re-confirm what was known. Certificate Transparency gives us the actual
 * set of hostnames that have ever been issued a certificate under each root.
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";

const ROOT_DOMAINS = ["dennisleehappy.org", "zekequiskitz.dpdns.org"];
const PRIMARY_ROOT = ROOT_DOMAINS[0];
const PORTFOLIO_URL = "https://www.dennisleehappy.org/en";

const REQUIRED_URLS = [
  "https://inclusive-ai-trust-gateway-web.vercel.app/",
  "https://jest-test-team.github.io/Agentic-Defense-Matrix-ADM/?api=https://api.dennisleehappy.org&gw=https://api.dennisleehappy.org",
];

// Hosts outside the root domains that still belong in the report.
const EXTRA_HOSTS = [
  "inclusive-ai-trust-gateway-web.vercel.app",
  "ielts-game.vercel.app",
];

/**
 * Hosts that resolve but are not the owner's work. `eth-gateway` is a CNAME to
 * Cloudflare's own Ethereum gateway, so it answers with Cloudflare's docs page.
 */
const NOT_OWNED_HOSTS = new Set(["eth-gateway.dennisleehappy.org"]);

/**
 * Real apps that happen to ship a framework's default <title>. Without this the
 * placeholder rule would throw them away.
 */
const REAL_DESPITE_DEFAULT_TITLE = new Set([
  "qu-lab.dennisleehappy.org",
  "web3.dennisleehappy.org",
]);

const DEFAULT_TITLES = new Set([
  "create next app",
  "quasar app",
  "vite app",
  "react app",
  "vue app",
  "nuxt app",
]);

/** Scaffolds ship a description as well as a title, so an empty check is not enough. */
const DEFAULT_DESCRIPTIONS = new Set([
  "generated by create next app",
  "a quasar project",
  "web site created using create-react-app",
  "vite app",
]);

/**
 * Hosts confirmed by a previous successful run. crt.sh is the source of truth
 * for new discoveries but answers 502 often enough that CI cannot depend on it
 * alone; unioning this file in means a bad crt.sh day degrades to "no new
 * sites found" instead of "most of the portfolio disappeared".
 */
const KNOWN_HOSTS_FILE = "data/known-hosts.json";

const CT_ATTEMPTS = 3;
const CONCURRENCY = 12;
const TIMEOUT_MS = 20000;
// crt.sh aggregates a lot of log data and is routinely slower than a site probe.
const CT_TIMEOUT_MS = 120000;
const USER_AGENT = "dennisleehappy-site-discovery/2.0";

/* ------------------------------------------------------------------ utils */

function normalizeUrl(rawUrl) {
  try {
    const url = new URL(rawUrl.replaceAll("&amp;", "&"));
    url.hash = "";
    return url.toString();
  } catch {
    return null;
  }
}

function extractUrls(text) {
  const matches = text.match(/https?:\/\/[^\s"'<>),]+/g) ?? [];
  return matches.map(normalizeUrl).filter(Boolean);
}

function hostOf(rawUrl) {
  try {
    return new URL(rawUrl).host.toLowerCase();
  } catch {
    return null;
  }
}

async function withTimeout(url, init = {}, timeoutMs = TIMEOUT_MS) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), timeoutMs);
  try {
    return await fetch(url, {
      ...init,
      signal: controller.signal,
      headers: { "user-agent": USER_AGENT, ...(init.headers ?? {}) },
    });
  } finally {
    clearTimeout(timer);
  }
}

async function mapWithConcurrency(items, worker) {
  const results = [];
  let cursor = 0;
  await Promise.all(
    Array.from({ length: Math.min(CONCURRENCY, items.length) }, async () => {
      while (cursor < items.length) {
        const index = cursor++;
        results[index] = await worker(items[index]);
      }
    }),
  );
  return results;
}

/* ------------------------------------------------------------ enumerate */

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function enumerateFromCertificateTransparency(rootDomain) {
  const endpoint = `https://crt.sh/?q=%25.${encodeURIComponent(rootDomain)}&output=json`;

  for (let attempt = 1; attempt <= CT_ATTEMPTS; attempt += 1) {
    try {
      const res = await withTimeout(endpoint, {}, CT_TIMEOUT_MS);
      if (!res.ok) throw new Error(`HTTP ${res.status}`);

      const entries = await res.json();
      const hosts = new Set();
      for (const entry of entries) {
        for (const name of String(entry.name_value ?? "").split("\n")) {
          const host = name.trim().toLowerCase().replace(/^\*\./, "");
          if (host.endsWith(rootDomain)) hosts.add(host);
        }
      }
      console.log(`crt.sh: ${hosts.size} hosts for ${rootDomain}`);
      return [...hosts];
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      if (attempt === CT_ATTEMPTS) {
        console.warn(`crt.sh lookup failed for ${rootDomain} after ${CT_ATTEMPTS} attempts: ${message}`);
        return [];
      }
      console.warn(`crt.sh attempt ${attempt} failed for ${rootDomain} (${message}); retrying`);
      await sleep(attempt * 5000);
    }
  }

  return [];
}

async function readKnownHosts() {
  try {
    const parsed = JSON.parse(await readFile(KNOWN_HOSTS_FILE, "utf8"));
    return Array.isArray(parsed.hosts) ? parsed.hosts : [];
  } catch {
    return [];
  }
}

async function enumerateHosts() {
  const hosts = new Set(EXTRA_HOSTS);

  for (const host of await readKnownHosts()) hosts.add(host);

  const perRoot = await Promise.all(ROOT_DOMAINS.map(enumerateFromCertificateTransparency));
  for (const list of perRoot) {
    for (const host of list) hosts.add(host);
  }

  // Keep scraping known sources so a site that never got its own certificate
  // (for example one behind a wildcard) is still covered.
  const sources = [];
  for (const file of ["data/projects.ts", "data/index.ts"]) {
    try {
      sources.push(await readFile(file, "utf8"));
    } catch {
      /* optional source */
    }
  }
  try {
    const res = await withTimeout(PORTFOLIO_URL);
    if (res.ok) sources.push(await res.text());
  } catch {
    /* optional source */
  }

  for (const source of sources) {
    for (const url of extractUrls(source)) {
      const host = hostOf(url);
      if (host && ROOT_DOMAINS.some((root) => host.endsWith(root))) hosts.add(host);
    }
  }

  for (const host of NOT_OWNED_HOSTS) hosts.delete(host);

  return [...hosts].sort();
}

/* ---------------------------------------------------------------- probe */

function readMeta(body, pattern) {
  const match = body.match(pattern);
  return match ? match[1].replace(/\s+/g, " ").trim() : "";
}

function decodeEntities(value) {
  return value
    .replace(/&#x27;|&apos;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">");
}

async function probeTarget(url) {
  const host = hostOf(url) ?? url;
  const startedAt = Date.now();

  try {
    const res = await withTimeout(url, { redirect: "follow" });
    const contentType = res.headers.get("content-type") ?? "";

    let body = "";
    try {
      const buffer = await res.arrayBuffer();
      body = new TextDecoder("utf-8", { fatal: false }).decode(buffer.slice(0, 60000));
    } catch {
      /* body is optional */
    }

    return {
      host,
      url,
      ok: res.status >= 200 && res.status < 400,
      status: res.status,
      finalUrl: res.url || url,
      contentType,
      title: decodeEntities(readMeta(body, /<title[^>]*>([\s\S]{0,200}?)<\/title>/i)),
      description: decodeEntities(
        readMeta(body, /<meta[^>]+name=["']description["'][^>]+content=["']([^"']{0,300})/i),
      ),
      ogImage: readMeta(body, /<meta[^>]+property=["']og:image["'][^>]+content=["']([^"']{0,400})/i),
      hasAppRoot: /<div[^>]+id=["'](root|__next|app|__nuxt)["']/i.test(body),
      isJson: /application\/json/i.test(contentType) || /^\s*[{[]/.test(body),
      latencyMs: Date.now() - startedAt,
    };
  } catch (error) {
    return {
      host,
      url,
      ok: false,
      status: 0,
      finalUrl: null,
      contentType: "",
      title: "",
      description: "",
      ogImage: "",
      hasAppRoot: false,
      isJson: false,
      latencyMs: Date.now() - startedAt,
      error: error instanceof Error ? error.message : String(error),
    };
  }
}

/* ------------------------------------------------------------- classify */

/**
 * Hostname shapes that name an API rather than a site. Note that a bare
 * "gateway" is deliberately absent: inclusive-ai-trust-gateway serves a real
 * single-page app, so "gateway" only counts as an API signal alongside a JSON
 * body (handled in classify()).
 */
const API_HOST_PATTERNS = [
  /(^|[.-])api(v\d+)?([.-]|$)/,
  /(^|[.-])backend?n?([.-]|$)/,
  /(^|[.-])backen([.-]|$)/,
  /(^|[.-])kong-/,
  /(^|[.-])r2-logs([.-]|$)/,
  /-monitor([.-]|$)/,
];

function looksLikeApiHost(host) {
  return API_HOST_PATTERNS.some((pattern) => pattern.test(host));
}

function classify(probe) {
  const { host, title, description } = probe;
  const normalizedTitle = title.trim().toLowerCase();

  if (!probe.ok) return "dead";

  if (looksLikeApiHost(host)) return "api";
  if (probe.isJson) return "api";
  if (/gateway/.test(host) && probe.isJson) return "api";

  if (/sign in .* cloudflare access/i.test(title)) return "gated";

  const normalizedDescription = description.trim().toLowerCase();
  const hasRealDescription =
    Boolean(normalizedDescription) && !DEFAULT_DESCRIPTIONS.has(normalizedDescription);

  if (
    DEFAULT_TITLES.has(normalizedTitle) &&
    !hasRealDescription &&
    !REAL_DESPITE_DEFAULT_TITLE.has(host)
  ) {
    return "placeholder";
  }

  return "frontend";
}

/* --------------------------------------------------------------- dedupe */

function identityKey(probe) {
  const title = probe.title.trim().toLowerCase();
  // A framework's default title says nothing about identity, so those hosts are
  // never collapsed into one another.
  if (!title || DEFAULT_TITLES.has(title)) return null;
  return title;
}

/**
 * Prefer the host a human would link to: the primary root domain first, then
 * the shortest hostname, then alphabetical so the choice is stable across runs.
 */
function preferredHost(a, b) {
  const aPrimary = a.host.endsWith(PRIMARY_ROOT);
  const bPrimary = b.host.endsWith(PRIMARY_ROOT);
  if (aPrimary !== bPrimary) return aPrimary ? a : b;
  if (a.host.length !== b.host.length) return a.host.length < b.host.length ? a : b;
  return a.host < b.host ? a : b;
}

function dedupeFrontends(frontends) {
  const canonicalByKey = new Map();
  const duplicates = [];

  for (const probe of frontends) {
    const key = identityKey(probe);
    if (key === null) {
      canonicalByKey.set(`host:${probe.host}`, probe);
      continue;
    }

    const existing = canonicalByKey.get(key);
    if (!existing) {
      canonicalByKey.set(key, probe);
      continue;
    }

    const winner = preferredHost(existing, probe);
    const loser = winner === existing ? probe : existing;
    canonicalByKey.set(key, winner);
    duplicates.push({
      host: loser.host,
      url: loser.url,
      duplicateOf: winner.host,
      title: loser.title,
      reason: "Identical title and description",
    });
  }

  return { canonical: [...canonicalByKey.values()], duplicates };
}

/* ----------------------------------------------------------------- main */

function summarize(probe) {
  return {
    host: probe.host,
    url: probe.url,
    status: probe.status,
    finalUrl: probe.finalUrl,
    contentType: probe.contentType || null,
    title: probe.title || null,
    description: probe.description || null,
    ogImage: probe.ogImage || null,
    latencyMs: probe.latencyMs,
    required: REQUIRED_URLS.includes(probe.url),
    ...(probe.error ? { error: probe.error } : {}),
  };
}

async function main() {
  const hosts = await enumerateHosts();
  console.log(`Enumerated ${hosts.length} hosts across ${ROOT_DOMAINS.join(", ")}`);

  // Required URLs are probed verbatim: the ADM demo lives on a path, and its
  // host root 404s, so checking the root would report a false outage.
  const targets = [...new Set([...hosts.map((host) => `https://${host}/`), ...REQUIRED_URLS])];
  const probes = await mapWithConcurrency(targets, probeTarget);

  const buckets = { frontend: [], api: [], gated: [], placeholder: [], dead: [] };
  for (const probe of probes) buckets[classify(probe)].push(probe);

  const { canonical, duplicates } = dedupeFrontends(buckets.frontend);
  canonical.sort((a, b) => a.host.localeCompare(b.host));

  const byHost = (a, b) => a.host.localeCompare(b.host);
  const report = {
    generatedAt: new Date().toISOString(),
    roots: ROOT_DOMAINS,
    portfolioUrl: PORTFOLIO_URL,
    summary: {
      enumeratedHosts: hosts.length,
      liveHosts: probes.filter((probe) => probe.ok).length,
      frontends: canonical.length,
      apisExcluded: buckets.api.length,
      gated: buckets.gated.length,
      placeholders: buckets.placeholder.length,
      dead: buckets.dead.length,
      duplicates: duplicates.length,
      requiredUrls: REQUIRED_URLS.length,
      requiredLiveUrls: probes.filter((probe) => probe.ok && REQUIRED_URLS.includes(probe.url))
        .length,
    },
    frontends: canonical.map(summarize),
    apis: buckets.api.sort(byHost).map(summarize),
    gated: buckets.gated.sort(byHost).map(summarize),
    placeholders: buckets.placeholder.sort(byHost).map(summarize),
    dead: buckets.dead.sort(byHost).map(summarize),
    duplicates: duplicates.sort((a, b) => a.host.localeCompare(b.host)),
  };

  await mkdir("data", { recursive: true });
  await writeFile("data/site-discovery-report.json", `${JSON.stringify(report, null, 2)}\n`);
  await writeFile(
    KNOWN_HOSTS_FILE,
    `${JSON.stringify({ updatedAt: report.generatedAt, hosts }, null, 2)}\n`,
  );

  const failedRequired = probes.filter(
    (probe) => REQUIRED_URLS.includes(probe.url) && !probe.ok,
  );
  if (failedRequired.length > 0) {
    console.error("Required URLs failed:", failedRequired.map((probe) => probe.url).join(", "));
    process.exitCode = 1;
  }

  const { summary } = report;
  console.log(
    `${summary.frontends} frontends | ${summary.apisExcluded} APIs excluded | ` +
      `${summary.gated} gated | ${summary.placeholders} placeholders | ` +
      `${summary.duplicates} duplicates | ${summary.dead} dead | ` +
      `${summary.requiredLiveUrls}/${summary.requiredUrls} required live.`,
  );
}

await main();
